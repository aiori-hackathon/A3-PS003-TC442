"""
STEP 6 - Write reports/RESULTS.md from the saved results.

    python step6_make_report.py            # real results -> reports/RESULTS.md
    python step6_make_report.py --quick    # smoke test -> reports/RESULTS_quick.md

Every number in the report is read from results/ - nothing is typed by hand.
Experiments without results are listed as NOT YET RUN.
"""
import sys
from datetime import date

import numpy as np

from src import config
from src.experiments import EXPERIMENTS
from src.results import load_all, rounds_to_reach, summarize
from src.utils import load_json

LABELS = {
    "persistence": "Persistence baseline (next = current)",
    "centralized": "Centralised MLP",
    "fedavg_iid": "FedAvg, IID clients",
    "fedavg_noniid": "FedAvg, non-IID clients",
    "local_only_noniid": "Local-only (no collaboration), non-IID",
    "pulsefed_noniid": "PulseFed (update-aware participation), non-IID",
    "pulsefed_v2_noniid": "PulseFed v2 (reuses sleeping clients' last update), non-IID",
    "fedprox_noniid": "FedProx (mu=%s), non-IID" % config.FEDPROX_MU,
    "fedavg_noniid_fp16": "FedAvg non-IID + FP16 uplink",
    "fedavg_noniid_int8": "FedAvg non-IID + INT8 uplink",
}


def fmt(m, s, d=4):
    if m is None:
        return "-"
    return f"{m:.{d}f}" + (f" ± {s:.{d}f}" if s is not None else "")


def mb(b):
    return f"{b / 1e6:.3f} MB" if b else "-"


def main() -> int:
    if "--quick" in sys.argv:
        config.use_quick_outputs()
    results = load_all()
    summary = summarize(results)
    prep_path = config.REPORTS_DIR / "preprocessing.json"
    prep = load_json(prep_path) if prep_path.exists() else None
    L = []
    add = L.append

    add("# PS-003 - Federated Traffic-Flow Prediction with Communication-Cost Evaluation")
    add(f"*Auto-generated by `step6_make_report.py` on {date.today().isoformat()}. "
        "All numbers are read from `results/`.*\n")

    missing = [n for n in EXPERIMENTS if n not in results]
    quick = [n for n, r in summary.items() if r["quick_mode"]]
    few_seeds = [n for n, r in summary.items() if r["n_seeds"] < len(config.SEEDS)]
    add("## Status")
    if not missing and not quick and not few_seeds:
        add(f"All {len(EXPERIMENTS)} experiments completed with {len(config.SEEDS)} seeds.\n")
    if missing:
        add("**NOT YET RUN:** " + ", ".join(f"`{n}`" for n in missing) + "\n")
    if quick:
        add("**WARNING - QUICK SMOKE-TEST RESULTS (3 rounds), NOT FINAL:** "
            + ", ".join(f"`{n}`" for n in quick) + "\n")
    if few_seeds:
        add("**Fewer than 3 seeds:** " + ", ".join(f"`{n}`" for n in few_seeds) + "\n")

    # ------------------------------------------------------------------ dataset
    add("## 1. Dataset")
    add("UCI Machine Learning Repository, *Traffic Flow Forecasting* (id 608, CC BY 4.0; "
        "Zhao, 2019, doi:10.24432/C57897; original paper: Zhao, Gkountouna & Pfoser, ACM TSAS 2019, "
        "doi:10.1145/3339823). Traffic volume every 15 minutes at 36 sensors on two "
        "highways in Northern Virginia / Washington D.C. Task: predict each sensor's volume "
        "15 minutes ahead.\n")
    if prep:
        m = prep["meta"]
        add("| Property | Value |\n|---|---|")
        add(f"| Training time steps | {m['num_train_steps']} |")
        add(f"| Test time steps (held out, later period) | {m['num_test_steps']} |")
        add(f"| Sensors | {m['num_sensors']} |")
        add(f"| Raw features per sensor | {m['num_raw_features']} |")
        add(f"| Model input features | {m['num_features_model']} |")
        add(f"| Missing values found (X_tr / Y_tr / X_te / Y_te) | {m['missing_X_tr']} / "
            f"{m['missing_Y_tr']} / {m['missing_X_te']} / {m['missing_Y_te']} |")
        add(f"| Consecutive 15-min rows (train / test) | {m['temporal_order_match_train']:.1%} / "
            f"{m['temporal_order_match_test']:.1%} |")
        add(f"| Test period starts one step after training ends | {m['train_test_boundary_match']:.1%} of sensors |")
        off = m.get("dataset_target_steps_ahead")
        add(f"| Provided target (`tra_Y`) | {off} step(s) = {15 * off} min after the newest lag |" if off
            else "| Provided target (`tra_Y`) | offset could not be determined |")
        add(f"| Target used in this project | "
            + ("value 15 min after the newest reading (rebuilt from consecutive rows)" if m.get("target_mode") == "next_15min"
               else "provided target, unchanged") + " |\n")
        add("**Data-integrity findings.** Our audit (`step2b_diagnose_layout.py`) found that the file "
            "differs from its documentation in three ways, and we handle each explicitly:")
        add("1. **48 columns, not 47:** 10 lags (oldest to newest), a 5-category day indicator (documented as 7 weekdays), "
            "24 hour-of-day columns, number of lanes, 4 direction columns and a 4-column one-hot road name.")
        if off == 2:
            add("2. **Target horizon:** the provided target is 2 steps (30 min) after the newest lag in the same row. "
                "Because every row's lag window is the previous window shifted by one step, the true next-15-minute "
                "value can be read from the next row; we use that as our target (set `TARGET_MODE = \"dataset\"` "
                "in `src/config.py` to use the provided target instead).")
        if m["train_test_boundary_match"] > 0.99 and m["temporal_order_match_train"] > 0.99:
            add("3. **Time order:** the documentation's dates suggest the test period lies before the training period, "
                "but the lag windows show the training rows are consecutive and the first test row follows the last "
                "training row directly. The provided split is therefore a valid chronological split (train earlier, test later).\n")
        else:
            add("3. **Time order:** WARNING - rows are not fully consecutive; check `step2b_diagnose_layout.py`.\n")
    else:
        add("**NOT YET RUN:** `step3_prepare_data.py` (dataset statistics unavailable).\n")

    # -------------------------------------------------------------- methodology
    add("## 2. Methodology")
    add("- **Features:** the 10 most recent volumes, their mean, standard deviation, last change and "
        "10-step trend, hour of day (sine/cosine), the day indicator, road direction and road name (one-hot) "
        "and number of lanes. Volumes are already scaled to 0-1 in the file, so errors are in those units.")
    add("- **Split:** the dataset's training period is used for training and the later test period "
        "for evaluation only. Standardisation statistics come from training data only.")
    add("- **Federated standardisation:** each client sends only its row count, feature sums and sums "
        "of squares; the server combines them into the same mean/std a pooled scaler would compute "
        "(verified by a unit test). These bytes are included in the communication cost.")
    add(f"- **Clients:** {config.NUM_CLIENTS} simulated intersections. *IID*: all training rows shuffled "
        "and dealt evenly. *Non-IID*: each sensor belongs to one client; sensors sorted by mean training "
        "volume and cut into contiguous groups (quietest to busiest roads).")
    add(f"- **Model:** identical MLP everywhere ({'-'.join(map(str, config.HIDDEN_SIZES))} hidden units, "
        "ReLU, NumPy implementation), MSE loss, Adam (lr %s), batch %d." % (config.LEARNING_RATE, config.BATCH_SIZE))
    add(f"- **FedAvg:** {config.NUM_ROUNDS} rounds x {config.LOCAL_EPOCHS} local epoch(s); aggregation "
        "weighted by client sample counts. Centralised training uses the same total number of epochs.")
    add("- **Communication cost:** length of the real serialized byte payloads (`numpy.savez`); downlink counts one "
        "copy per client.")
    add("- **Evaluation:** MAE and RMSE in original volume units on the same test period for every "
        "method; final model after a fixed budget (the test set is never used for tuning).")
    add(f"- **Seeds:** {config.SEEDS}; mean ± sample standard deviation reported.\n")

    # ------------------------------------------------------------------ results
    add("## 3. Prediction accuracy (test period)")
    add("| Method | MAE | RMSE | Seeds | Beyond PS-003 minimum |\n|---|---|---|---|---|")
    for n in EXPERIMENTS:
        extra = "yes" if EXPERIMENTS[n]["extra"] else ""
        if n in summary:
            r = summary[n]
            add(f"| {LABELS[n]} | {fmt(r['mae_mean'], r['mae_std'])} | "
                f"{fmt(r['rmse_mean'], r['rmse_std'])} | {r['n_seeds']} | {extra} |")
        else:
            add(f"| {LABELS[n]} | NOT YET RUN | NOT YET RUN | 0 | {extra} |")
    add("")
    add("<details><summary>Per-seed values</summary>\n")
    add("| Method | Seed | MAE | RMSE |\n|---|---|---|---|")
    for n, runs in results.items():
        for r in runs:
            add(f"| {n} | {r['seed']} | {r['final']['mae']:.4f} | {r['final']['rmse']:.4f} |")
    add("\n</details>\n")

    c = summary.get("centralized")
    if c:
        add("**Gap to centralised (MAE):**")
        for n in ["fedavg_iid", "fedavg_noniid", "pulsefed_noniid", "pulsefed_v2_noniid", "fedprox_noniid", "local_only_noniid", "persistence"]:
            if n in summary:
                gap = (summary[n]["mae_mean"] - c["mae_mean"]) / c["mae_mean"] * 100
                add(f"- {LABELS[n]}: {gap:+.1f}%")
        add("")

    # ------------------------------------------------------------- communication
    add("## 4. Communication cost")
    add("| Method | Bytes per round (mean) | Total incl. setup | MAE |\n|---|---|---|---|")
    for n in ["fedavg_iid", "fedavg_noniid", "pulsefed_noniid", "pulsefed_v2_noniid", "fedprox_noniid", "fedavg_noniid_fp16", "fedavg_noniid_int8"]:
        if n in results:
            cm = results[n][0]["comm"]
            add(f"| {LABELS[n]} | {cm['bytes_per_round_mean'] / 1e3:.1f} KB | {mb(cm['total_bytes'])} | "
                f"{fmt(summary[n]['mae_mean'], summary[n]['mae_std'])} |")
        else:
            add(f"| {LABELS[n]} | NOT YET RUN | NOT YET RUN | NOT YET RUN |")
    add("")
    if "fedavg_noniid" in results:
        cm = results["fedavg_noniid"][0]["comm"]
        raw = cm["raw_volume_only_bytes"]
        s = prep["meta"]["num_sensors"] if prep else 36
        per_day = s * 96 * 4
        add(f"- Model size: {results['fedavg_noniid'][0]['model_params']:,} parameters "
            f"= {cm['model_float32_bytes'] / 1e3:.1f} KB as float32; one serialized payload adds "
            f"format overhead (measured downlink per client: {cm['downlink_bytes_per_round'] / results['fedavg_noniid'][0]['num_clients'] / 1e3:.1f} KB).")
        add(f"- Uploading the raw training volumes once (float32, one value per sensor per step) "
            f"would cost {mb(raw)}; full feature rows cost "
            + (mb(results['centralized'][0]['comm']['raw_feature_rows_bytes']) if 'centralized' in results else "n/a")
            + ".")
        add(f"- **Break-even:** one full FedAvg training ({mb(cm['total_bytes'])}) costs as much as "
            f"streaming raw volumes from {s} sensors for {cm['total_bytes'] / per_day:.1f} days. "
            "FedAvg cost depends on model size x rounds, while raw streaming grows with time and "
            "number of sensors, so FL saves bandwidth only for long deployments, many sensors, or "
            "richer raw data (e.g. video). This is a computed estimate from measured payload sizes.\n")

    # --------------------------------------------------------------- convergence
    add("## 5. Convergence")
    if c and any(n in results for n in ["fedavg_iid", "fedavg_noniid"]):
        target = c["mae_mean"] * 1.05
        add(f"Rounds needed to reach within 5% of centralised MAE (target MAE {target:.4f}):\n")
        add("| Method | Rounds to target (per seed) | Final-round MAE |\n|---|---|---|")
        for n in ["fedavg_iid", "fedavg_noniid", "pulsefed_noniid", "pulsefed_v2_noniid", "fedprox_noniid", "fedavg_noniid_fp16", "fedavg_noniid_int8"]:
            if n in results:
                rr = [rounds_to_reach(r["history"], target) for r in results[n]]
                txt = ", ".join("not reached" if x is None else str(x) for x in rr)
                add(f"| {LABELS[n]} | {txt} | {fmt(summary[n]['mae_mean'], summary[n]['mae_std'])} |")
        add("\nSee `figures/02_convergence_iid_vs_noniid.png`.\n")
    else:
        add("NOT YET RUN (needs centralised and FedAvg results).\n")

    # ----------------------------------------------------------------- pulsefed
    add("## 6. PulseFed participation")
    if "pulsefed_noniid" in results and "fedavg_noniid" in results:
        pr, fr = results["pulsefed_noniid"], results["fedavg_noniid"]
        up = [r["comm"]["uploads_total"] for r in pr]
        allu = pr[0]["comm"]["uploads_if_all_clients"]
        byte_ratio = np.mean([p["comm"]["total_bytes"] for p in pr]) / np.mean([f["comm"]["total_bytes"] for f in fr])
        dm = summary["pulsefed_noniid"]["mae_mean"] - summary["fedavg_noniid"]["mae_mean"]
        add(f"- Rule: clients at or above the average update size talk; at least {config.PULSE_MIN_ACTIVE} "
            f"talk every round; no client sleeps more than {config.PULSE_MAX_SLEEP} rounds in a row; round 1 includes everyone.")
        add(f"- Uploads per run: {', '.join(map(str, up))} (per seed) vs {allu} for FedAvg.")
        add(f"- Total bytes (incl. control messages): {byte_ratio:.0%} of FedAvg non-IID.")
        add(f"- MAE change vs FedAvg non-IID: {dm:+.4f}.")
        add("- See `figures/08_pulsefed_participation.png` and the per-client table below "
            "(does PulseFed silence quiet roads?).\n")
    else:
        add("NOT YET RUN (needs `pulsefed_noniid` and `fedavg_noniid`).\n")

    add("**PulseFed v2 (follow-up, rule fixed before running).** Same selection rule as PulseFed; the only "
        "change is that the server reuses each sleeping client's most recent update, so every road group "
        "always counts in the average. No extra bytes are sent.\n")
    if "pulsefed_v2_noniid" in results and "fedavg_noniid" in results and "pulsefed_noniid" in results:
        v2 = results["pulsefed_v2_noniid"]
        b2 = np.mean([r["comm"]["total_bytes"] for r in v2]) / np.mean([f["comm"]["total_bytes"] for f in results["fedavg_noniid"]])
        add(f"- Uploads per run: {', '.join(str(r['comm']['uploads_total']) for r in v2)} (per seed).")
        add(f"- Total bytes: {b2:.0%} of FedAvg non-IID.")
        add(f"- MAE: {fmt(summary['pulsefed_v2_noniid']['mae_mean'], summary['pulsefed_v2_noniid']['mae_std'])} "
            f"vs PulseFed {fmt(summary['pulsefed_noniid']['mae_mean'], summary['pulsefed_noniid']['mae_std'])} "
            f"vs FedAvg non-IID {fmt(summary['fedavg_noniid']['mae_mean'], summary['fedavg_noniid']['mae_std'])}.")
        add("- See `figures/09_pulsefed_v2_participation.png`.\n")
    else:
        add("PulseFed v2: NOT YET RUN.\n")

    # ------------------------------------------------------------ heterogeneity
    add("## 7. Data heterogeneity and per-client results")
    if prep:
        hi, hn = prep["heterogeneity_iid"], prep["heterogeneity_noniid"]
        add("Heterogeneity score = Wasserstein distance between a client's target distribution and the "
            "global one, divided by the global standard deviation (0 = identical).\n")
        add("| Client | IID rows | IID score | Non-IID rows | Non-IID mean volume | Non-IID score |\n|---|---|---|---|---|---|")
        for k in range(len(hn["per_client_distance"])):
            add(f"| {k} | {hi['per_client_samples'][k]:,} | {hi['per_client_distance'][k]:.3f} | "
                f"{hn['per_client_samples'][k]:,} | {hn['per_client_mean_target'][k]:.3f} | "
                f"{hn['per_client_distance'][k]:.3f} |")
        add(f"| **mean** | | **{hi['mean_distance']:.3f}** | | | **{hn['mean_distance']:.3f}** |\n")
    rows = [n for n in ["centralized", "fedavg_noniid", "pulsefed_noniid", "pulsefed_v2_noniid", "local_only_noniid"] if n in results]
    if rows:
        k_count = len(results[rows[0]][0]["final"]["per_client"])
        add("Test MAE on each non-IID client's own sensors (mean over seeds):\n")
        add("| Method | " + " | ".join(f"Client {k}" for k in range(k_count)) + " |")
        add("|---|" + "---|" * k_count)
        for n in rows:
            per = np.mean([[c_["mae"] for c_ in r["final"]["per_client"]] for r in results[n]], axis=0)
            add(f"| {LABELS[n]} | " + " | ".join(f"{v:.4f}" for v in per) + " |")
        add("")

    # ------------------------------------------------------------------ figures
    add("## 8. Figures")
    for f, cap in [("00_raw_traffic.png", "Raw traffic, quietest vs busiest sensor"),
                   ("01_accuracy_comparison.png", "MAE / RMSE of all methods"),
                   ("02_convergence_iid_vs_noniid.png", "Test error per round, IID vs non-IID"),
                   ("03_communication_cost.png", "Cumulative and per-round bytes"),
                   ("04_accuracy_vs_bytes.png", "Accuracy vs communication trade-off"),
                   ("05_actual_vs_predicted.png", "Actual vs predicted traffic"),
                   ("06_per_client_fairness.png", "Per-client accuracy"),
                   ("07_client_distributions.png", "Client data distributions"),
                   ("08_pulsefed_participation.png", "PulseFed: who talked in which round"),
                   ("09_pulsefed_v2_participation.png", "PulseFed v2: who talked in which round")]:
        if (config.FIGURES_DIR / f).exists():
            add(f"**{cap}**\n\n![{cap}](../{config.FIGURES_DIR.name}/{f})\n")
        else:
            add(f"- {cap}: NOT YET GENERATED (`step5_make_plots.py" + (" --quick" if config.QUICK_MODE else "") + "`)")
    add("")

    # -------------------------------------------------------------- limitations
    add("## 9. Limitations")
    add("- Simulation on one machine: no real network latency, packet loss or client drop-out.")
    add("- One dataset (36 sensors, about 3 weeks); results may not transfer to other cities.")
    add("- Partial participation is studied only through PulseFed; random client sampling and client drop-out are not.")
    add("- No formal privacy guarantee (no differential privacy or secure aggregation), as allowed by PS-003. "
        "Model updates can still leak information.")
    add("- Fixed hyper-parameters, not tuned per method; a validation-based tuning could change the gaps.")
    add("- Payload sizes include `.npz` container overhead (compare measured payload vs float32 model size in Section 4); a custom binary format would be smaller.\n")

    add("## 10. Conclusions")
    add("*Automatic factual summary (the team should add its own interpretation below):*\n")
    if c:
        best = min(summary, key=lambda n: summary[n]["mae_mean"])
        add(f"- Lowest mean test MAE: **{LABELS[best]}** ({summary[best]['mae_mean']:.4f}).")
        if "persistence" in summary:
            beat = c["mae_mean"] < summary["persistence"]["mae_mean"]
            add(f"- The centralised MLP {'beats' if beat else 'does NOT beat'} the persistence baseline.")
        if "fedavg_iid" in summary and "fedavg_noniid" in summary:
            d = summary["fedavg_noniid"]["mae_mean"] - summary["fedavg_iid"]["mae_mean"]
            add(f"- Non-IID FedAvg MAE minus IID FedAvg MAE: {d:+.4f}.")
        if "fedavg_noniid" in summary and "local_only_noniid" in summary:
            better = summary["fedavg_noniid"]["mae_mean"] < summary["local_only_noniid"]["mae_mean"]
            add(f"- Collaboration via FedAvg is {'better' if better else 'NOT better'} than local-only training.")
        if "fedavg_noniid" in summary and "pulsefed_noniid" in summary:
            r = np.mean([x["comm"]["total_bytes"] for x in results["pulsefed_noniid"]]) / np.mean([x["comm"]["total_bytes"] for x in results["fedavg_noniid"]])
            dm = summary["pulsefed_noniid"]["mae_mean"] - summary["fedavg_noniid"]["mae_mean"]
            add(f"- PulseFed uses {r:.0%} of plain FedAvg's total bytes with an MAE change of {dm:+.4f}.")
        if "fedavg_noniid" in summary and "pulsefed_v2_noniid" in summary:
            r = np.mean([x["comm"]["total_bytes"] for x in results["pulsefed_v2_noniid"]]) / np.mean([x["comm"]["total_bytes"] for x in results["fedavg_noniid"]])
            dm = summary["pulsefed_v2_noniid"]["mae_mean"] - summary["fedavg_noniid"]["mae_mean"]
            add(f"- PulseFed v2 uses {r:.0%} of plain FedAvg's total bytes with an MAE change of {dm:+.4f}.")
        if "fedavg_noniid" in results and "fedavg_noniid_int8" in results:
            r = results["fedavg_noniid_int8"][0]["comm"]["total_bytes"] / results["fedavg_noniid"][0]["comm"]["total_bytes"]
            dm = summary["fedavg_noniid_int8"]["mae_mean"] - summary["fedavg_noniid"]["mae_mean"]
            add(f"- INT8 uplink uses {r:.0%} of plain FedAvg's total bytes with an MAE change of {dm:+.4f}.")
    else:
        add("NOT YET AVAILABLE - run the experiments first.")
    interp = config.REPORTS_DIR / "team_interpretation.md"
    if config.QUICK_MODE:
        add("\n*Quick smoke-test report - team interpretation omitted.*\n")
    elif interp.exists():
        add("\n### Team interpretation\n")
        add(interp.read_text(encoding="utf-8").strip() + "\n")
    else:
        add("\n*Team interpretation:* TODO - write it in `reports/team_interpretation.md`; "
            "it is inserted here every time the report is regenerated.\n")

    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    out = config.REPORTS_DIR / config.REPORT_NAME
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"Saved {out}")
    if missing or quick:
        print("Report contains NOT YET RUN / QUICK sections - run the full experiments for final results.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
